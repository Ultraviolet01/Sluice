// Writes docs/VERIFIED.md from the records the scripts save in
// contracts/deployments/<network>-*.json: the deployment, the demo company,
// every contract function used live, the agent's rounds, the live attack run
// and the proposal flood.
//
//   node scripts/verified.mjs                 Aevum Testnet -> docs/VERIFIED.md
//   node scripts/verified.mjs localhost out.md   preview from a local run
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const net = process.argv[2] || "aevumTestnet";
const out = process.argv[3] || "docs/VERIFIED.md";
const local = net === "localhost";
const load = (n) => {
  const f = `contracts/deployments/${net}-${n}.json`;
  return existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : null;
};
const tx = (h) => (h ? (local ? `\`${h.slice(0, 10)}…\`` : `[${h.slice(0, 10)}…](https://explorer-test.qday.info/tx/${h})`) : "");
const addr = (a) => (local ? `\`${a}\`` : `[\`${a}\`](https://explorer-test.qday.info/address/${a})`);

const deploy = load("deploy"), demo = load("demo"), attacks = load("attacks"), flood = load("flood"), fns = load("functions"), agent = load("agent");
const L = [];
L.push("# Verified on " + (local ? "a local Hardhat node (preview)" : "QDay Aevum Testnet"), "", "[Back to the README](../README.md)", "");
L.push("Each claim below was run against the live contracts; every transaction links to the explorer. Generated by `node scripts/verified.mjs` from the scripts' own records.", "");

if (deploy) {
  L.push("## Deployment", "", "| Contract | Address | Transaction |", "|---|---|---|");
  L.push(`| SluiceVault (owner ${addr(deploy.owner)}) | ${addr(deploy.vault)} | ${tx(deploy.vaultTx)} |`);
  L.push(`| SluiceFactory | ${addr(deploy.factory)} | ${tx(deploy.factoryTx)} |`);
  L.push(`| tUSD8 | ${addr(deploy.token)} | official, 6 decimals |`, "");
  if (!local) L.push("The source of both contracts is verified on the explorer (`node scripts/verify-explorer.mjs` in `contracts/`): open either address and choose the Contract tab.", "");
}
if (demo) {
  L.push("## The demo company, set up through the factory", "", `Vault ${addr(demo.vault)}, owner ${addr(demo.owner)}, agent ${addr(demo.agent)}.`, "", "| Step | Transaction |", "|---|---|");
  for (const t of demo.txs) L.push(`| ${t.what} | ${tx(t.tx)} |`);
  L.push("");
}
if (fns) {
  const tx_ = fns.rows.filter((r) => r.kind === "tx").length, ref = fns.rows.filter((r) => r.kind === "refused").length, vw = fns.rows.filter((r) => r.kind === "view").length;
  L.push("## Every contract function, used live", "", `A fresh company created through the factory (${addr(fns.vault)}), run by its owner, the agent and the Telegram bot's guardian key. **${fns.passed} of ${fns.rows.length} checks passed**: ${tx_} real transactions, each followed by a check of the state it changed; ${ref} calls that must be refused, simulated so the vault's own reason shows; ${vw} reads. Generated by \`npx hardhat run scripts/live-functions.js --network aevumTestnet\`.`, "");
  L.push("| Function | Caller | Result | Proof |", "|---|---|---|---|");
  for (const r of fns.rows) L.push(`| \`${r.fn}\` | ${r.who} | ${r.ok ? "" : "**FAIL** "}${r.check.replace(/\|/g, "\\|")} | ${r.tx ? tx(r.tx) : r.kind} |`);
  L.push("");
}
if (agent) {
  L.push("## The agent, live", "", `On the demo company ${addr(agent.vault)}:`, "", "| Round | What it did | Proof |", "|---|---|---|");
  for (const r of agent.rounds) L.push(`| ${r.where} | ${r.what} | ${r.tx ? tx(r.tx) : `[run log](${r.run})`} |`);
  L.push("");
}
if (attacks) {
  const pass = attacks.rows.filter((r) => r.ok).length;
  L.push("## A stolen agent key, against the live vault", "", `${pass} of ${attacks.rows.length} checks passed. Refusals are the vault's own answers to the attempted call; allowed actions are real transactions.`, "", "| Who | Tries to | Result |", "|---|---|---|");
  for (const r of attacks.rows) L.push(`| ${r.who} | ${r.what} | ${r.tx ? `done: ${tx(r.tx)}` : `${r.ok ? "refused" : "**NOT refused**"}: \`${r.result}\``} |`);
  L.push("");
}
if (flood) {
  L.push("## Proposal flood", "", `With the agent's key, ${flood.attempts} attempts to file proposals on a vault with ${flood.bills} listed bills: **${flood.accepted} accepted**, the rest refused because proposals are tied to the owner's bills, one per bill period that is due.`, "");
  L.push("| Refused because | Times |", "|---|---|");
  for (const [k, v] of Object.entries(flood.refused)) L.push(`| \`${k}\` | ${v} |`);
  L.push("", "The owner could still act during and after the flood:", "");
  for (const c of flood.ownerChecks) L.push(`- ${c.what}: ${tx(c.tx)}`);
  L.push("");
}
L.push("## Still to record", "");
if (!deploy) L.push("- Deployment (`cd contracts && npm run deploy`)");
if (!demo) L.push("- Demo company (`npm run demo:setup -- --network aevumTestnet`)");
if (!attacks) L.push("- Live attack run (`npm run attacks -- --network aevumTestnet`)");
if (!flood) L.push("- Proposal flood (`npm run flood -- --network aevumTestnet`)");
if (!fns) L.push("- Every function (`npm run functions -- --network aevumTestnet`)");
L.push("- A Telegram alert received", "- A company created from the dashboard, and the agent finding it through the factory", "");
writeFileSync(out, L.join("\n"));
console.log(`Wrote ${out}`);
